// allowFile is the counted allow-list of TestExportedDocs (SPL-1049).
const allowFile = "testdata/exported-doc-allow.txt"

// moduleRoot is the spool-hub-api module, two levels above this package.
const moduleRoot = "../.."

// TestExportedDocs is the SPL-1049 gate: every exported identifier in the
// module's non-test Go has a doc comment, except the ones the counted
// allow-list still holds.
func TestExportedDocs(t *testing.T) {
	hits, err := UndocumentedExports(moduleRoot)
	if err != nil {
		t.Fatal(err)
	}
	allow, err := readAllow(allowFile)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range checkAllow(hits, allow) {
		t.Error(p)
	}
}

// TestExportedDocsRedControl plants an undocumented exported func in a temp
// package: the gate must name it, and a documented twin must pass.
func TestExportedDocsRedControl(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "p/p.go", "package p\n\nfunc Undocumented() {}\n")
	hits, err := UndocumentedExports(dir)
	if err != nil {
		t.Fatal(err)
	}
	probs := checkAllow(hits, map[string]int{})
	if len(probs) != 1 || !strings.Contains(probs[0], "p/p.go:Undocumented") {
		t.Fatalf("red control: want one problem naming p/p.go:Undocumented, got %q", probs)
	}
	write(t, dir, "p/p.go", "package p\n\n// Documented has a comment.\nfunc Documented() {}\n")
	if hits, err = UndocumentedExports(dir); err != nil || len(hits) != 0 {
		t.Fatalf("documented twin: hits %q err %v", hits, err)
	}
}

// TestUndocumentedExportsRules pins what counts as documented.
func TestUndocumentedExportsRules(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "a/a.go", `package a

// T is documented.
type T struct{}

type U struct{}

func (T) Bare()     {}
func (*U) Ptr()     {}
func (t) hidden()   {}
func (t) Exported() {}

type t struct{}

// The group comment documents its members.
const (
	G1 = 1
	G2 = 2
)

const (
	// S1 has its own.
	S1 = 1
	S2 = 2
)

var V, W = 1, 2

func unexported() {}
`)
	write(t, dir, "a/a_test.go", "package a\n\nfunc TestOnly() {}\n")
	write(t, dir, "a/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage a\n\nfunc Gen() {}\n")
	write(t, dir, "testdata/x.go", "package x\n\nfunc Skipped() {}\n")
	got, err := UndocumentedExports(dir)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"a/a.go:S2", "a/a.go:T.Bare", "a/a.go:U", "a/a.go:U.Ptr", "a/a.go:V", "a/a.go:W"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %q, want %q", got, want)
	}
}

// TestCheckAllowOnlyShrinks: over the count fails, under the count fails
// until the line is lowered, a listed file with no hits fails until removed.
func TestCheckAllowOnlyShrinks(t *testing.T) {
	hits := []string{"a.go:X", "a.go:Y", "b.go:Z"}
	cases := []struct {
		allow map[string]int
		want  int
	}{
		{map[string]int{"a.go": 2, "b.go": 1}, 0},
		{map[string]int{"a.go": 1, "b.go": 1}, 1},
		{map[string]int{"a.go": 3, "b.go": 1}, 1},
		{map[string]int{"a.go": 2, "b.go": 1, "c.go": 1}, 1},
		{map[string]int{"a.go": 2}, 1},
	}
	for i, c := range cases {
		if got := checkAllow(hits, c.allow); len(got) != c.want {
			t.Errorf("case %d: %d problem(s) %q, want %d", i, len(got), got, c.want)
		}
	}
}

// checkAllow compares the hits with the allow-list and returns one problem
// per file whose count differs from its line, sorted.
func checkAllow(hits []string, allow map[string]int) []string {
	have := map[string][]string{}
	for _, h := range hits {
		file := h[:strings.LastIndex(h, ":")]
		have[file] = append(have[file], h)
	}
	var probs []string
	for file, hs := range have {
		switch n := allow[file]; {
		case len(hs) > n:
			probs = append(probs, fmt.Sprintf("%s: %d undocumented exported identifier(s), allow-list %d: add a doc comment to %s",
				file, len(hs), n, strings.Join(hs, ", ")))
		case len(hs) < n:
			probs = append(probs, fmt.Sprintf("%s: %d undocumented, allow-list %d: lower its line in %s to %d (it only shrinks)",
				file, len(hs), n, allowFile, len(hs)))
		}
	}
	for file := range allow {
		if len(have[file]) == 0 {
			probs = append(probs, fmt.Sprintf("%s: no undocumented identifier left: remove its line from %s", file, allowFile))
		}
	}
	sort.Strings(probs)
	return probs
}

// readAllow parses "<path> <count>" lines; # starts a comment.
func readAllow(path string) (map[string]int, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close() //nolint:errcheck
	out := map[string]int{}
	sc := bufio.NewScanner(f)
	for line := 1; sc.Scan(); line++ {
		s := strings.TrimSpace(sc.Text())
		if s == "" || strings.HasPrefix(s, "#") {
			continue
		}
		fs := strings.Fields(s)
		n, err := 0, fmt.Errorf("want <path> <count>")
		if len(fs) == 2 {
			n, err = strconv.Atoi(fs[1])
		}
		if err != nil || n < 1 {
			return nil, fmt.Errorf("%s:%d: %q: want <path> <count> with count >= 1", path, line, s)
		}
		if _, dup := out[fs[0]]; dup {
			return nil, fmt.Errorf("%s:%d: %s listed twice", path, line, fs[0])
		}
		out[fs[0]] = n
	}
	return out, sc.Err()
}

func write(t *testing.T, dir, rel, body string) {
	t.Helper()
	p := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}
