#!/usr/bin/env bash
#------------------------------------------------------------------------------
# Purpose: do_net_dns_fast_failover (networking round row 07, SPL-2625) puts
#   ipv4.dns 8.8.8.8,1.1.1.1 + ipv4.dns-options timeout:2,attempts:2 on every
#   uplink profile.
#   1. DRY_RUN default: lists every profile with what it holds now (by UUID,
#      never NAME), plans the changes, SKIPs non-uplink types, runs no modify;
#      a bad DRY_RUN, NET_DNS_REAPPLY and a relative NET_ROOT are refused
#   2. DRY_RUN=0: modifies exactly the profiles that miss a value, with only
#      ipv4.dns and ipv4.dns-options, reads each back, says PENDING for the
#      active device; a second run changes nothing (all SAME)
#   3. the order refusal: DRY_RUN=0 with resolv.conf a regular file, resolved's
#      stub or missing -> FATAL, no modify; a dry run notes it and plans
#   4. NET_DNS_REAPPLY=1: reapplies the active device, the plan's measuring
#      command reads nameserver 8.8.8.8 + options timeout:2 attempts:2 -> OK;
#      again -> no second reapply; a reapply that leaves resolv.conf stale
#      -> FATAL
#   5. reading: a modify that does not stick -> FATAL; nmcli's escaped
#      colons and another option order read as SAME; the nameservers in the
#      other order are changed
#   6. no uplink profile, no profile at all -> FATAL
#   7. red controls: a copy without the refusal, a copy writing timeout:5,
#      a copy with the nameservers swapped and a copy that also sets
#      ipv4.ignore-auto-dns are each caught
#   No real /etc, NetworkManager or interface: NET_ROOT, a stub nmcli, no sudo.
#------------------------------------------------------------------------------
set -uo pipefail
TEST_DIR=$(cd "$(dirname "$0")" && pwd)
PROJ_ROOT=$(cd "$TEST_DIR/../../.." && pwd)
FUNC="$PROJ_ROOT/src/bash/run/net-dns-fast-failover.func.sh"
fails=0
pass() { echo "PASS: $1"; }
fail() { echo "FAIL: $1"; fails=$((fails + 1)); }
bash -n "$FUNC" || { echo "FAIL: bash -n"; exit 1; }
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
mkdir -p "$T/bin"
export CALLS="$T/calls" ST="$T/state"
NMLINK=/run/NetworkManager/resolv.conf
W=11111111-1111-4111-8111-111111111111
E=22222222-2222-4222-8222-222222222222
S=33333333-3333-4333-8333-333333333333
L=44444444-4444-4444-8444-444444444444

# nmcli: the profile list is $ST/list, each property $ST/<uuid>.<field>;
# ESCAPE=1 prints colons the terse way (\:), MODIFY_NOOP=1 drops a modify,
# REAPPLY_WRITES=1 makes a reapply rewrite NM's resolv.conf from the profile
cat >"$T/bin/nmcli" <<'EOF'
#!/usr/bin/env bash
echo "nmcli $*" >>"$CALLS"
case "$1 $2 $3 $4" in
  "-t -f UUID,TYPE,ACTIVE,DEVICE connection") cat "$ST/list"; exit 0 ;;
esac
if [[ "$1" == -g && "$3 $4 $5" == "connection show uuid" ]]; then
  v="$(cat "$ST/$6.$2" 2>/dev/null)"
  [[ -n "${ESCAPE:-}" ]] && v="${v//:/\\:}"
  echo "$v"; exit 0
fi
if [[ "$1 $2 $3" == "connection modify uuid" ]]; then
  u="$4"; shift 4
  [[ -n "${MODIFY_NOOP:-}" ]] && exit 0
  while (($# >= 2)); do echo "$2" >"$ST/$u.$1"; shift 2; done
  exit 0
fi
if [[ "$1 $2" == "device reapply" ]]; then
  [[ -n "${REAPPLY_WRITES:-}" ]] || exit 0
  u="$(awk -v d="$3" -F: '$4 == d {print $1}' "$ST/list")"
  f="$NET_ROOT/run/NetworkManager/resolv.conf"; mkdir -p "${f%/*}"
  { echo '# Generated by NetworkManager'
    tr ',' '\n' <"$ST/$u.ipv4.dns" | sed 's/^/nameserver /'; echo 'nameserver 192.0.2.1'
    echo "options $(tr ',' ' ' <"$ST/$u.ipv4.dns-options")"; } >"$f"
  exit 0
fi
exit 1
EOF
chmod +x "$T/bin/nmcli"

# reset <root> <resolv: nm|stub|file|none> - fresh root, calls and profiles:
# W wifi active on wlan0 (dns set, options empty), E ethernet inactive
# (empty), S wifi inactive already on target, L loopback
reset() {
  rm -rf "$1" "$CALLS" "$ST"; mkdir -p "$1/etc" "$1/run/NetworkManager" "$ST"
  case "$2" in
    nm) ln -s "$NMLINK" "$1/etc/resolv.conf"; printf 'nameserver 192.0.2.1\nnameserver 8.8.8.8\n' >"$1$NMLINK" ;;
    stub) ln -s /run/systemd/resolve/stub-resolv.conf "$1/etc/resolv.conf" ;;
    file) echo 'nameserver 192.0.2.53' >"$1/etc/resolv.conf" ;;
  esac
  printf '%s\n' "$W:802-11-wireless:yes:wlan0" "$E:802-3-ethernet:no:" "$S:802-11-wireless:no:" "$L:loopback:yes:lo" >"$ST/list"
  echo 8.8.8.8,1.1.1.1 >"$ST/$W.ipv4.dns"; : >"$ST/$W.ipv4.dns-options"
  : >"$ST/$E.ipv4.dns"; : >"$ST/$E.ipv4.dns-options"
  echo 8.8.8.8,1.1.1.1 >"$ST/$S.ipv4.dns"; echo timeout:2,attempts:2 >"$ST/$S.ipv4.dns-options"
  : >"$CALLS"
}
# run <func file> <root> [VAR=val ...] - the action in a clean subshell
run() {
  local f="$1" root="$2"; shift 2
  env NET_ROOT="$root" NET_NMCLI="$T/bin/nmcli" NET_SUDO="" "$@" bash -c '
    do_log() { printf "%s\n" "$*"; }
    source "$0"; do_net_dns_fast_failover' "$f"
}
held() { echo "$(cat "$ST/$1.ipv4.dns") $(cat "$ST/$1.ipv4.dns-options")"; }
target="8.8.8.8,1.1.1.1 timeout:2,attempts:2"
modifies() { grep -c 'connection modify' "$CALLS"; }

# 1. dry run
reset "$T/r1" nm; out="$(run "$FUNC" "$T/r1" 2>&1)"; rc=$?
if ((rc == 0)) && (($(modifies) == 0)) && [[ "$(held "$E")" == " " ]] &&
  grep -q "NOW resolv.conf -> $NMLINK" <<<"$out" &&
  grep -q "NOW $W type=802-11-wireless active=yes device=wlan0 ipv4.dns=8.8.8.8,1.1.1.1 ipv4.dns-options=none" <<<"$out" &&
  grep -q "NOW $E type=802-3-ethernet active=no device=- ipv4.dns=none ipv4.dns-options=none" <<<"$out" &&
  grep -qx "PLAN nmcli connection modify uuid $W ipv4.dns 8.8.8.8,1.1.1.1 ipv4.dns-options timeout:2,attempts:2" <<<"${out//$T\/bin\//}" &&
  grep -q "PLAN .*modify uuid $E " <<<"$out" && grep -qx "SAME $S" <<<"$out" &&
  grep -q "SKIP $L type=loopback" <<<"$out" && grep -q 'OK DRY_RUN 2 of 3 uplink' <<<"$out"; then
  pass "1 DRY_RUN default lists, plans 2 of 3, SKIPs loopback, modifies nothing"
else fail "1 dry run (rc=$rc): $out / $(cat "$CALLS")"; fi
! grep -qi 'NAME' "$CALLS" && pass "1 nmcli is never asked for NAME" || fail "1 NAME asked: $(cat "$CALLS")"
out="$(run "$FUNC" "$T/r1" DRY_RUN=yes 2>&1)" && fail "1 DRY_RUN=yes accepted" || pass "1 bad DRY_RUN refused"
out="$(run "$FUNC" "$T/r1" NET_DNS_REAPPLY=yes 2>&1)" && fail "1 NET_DNS_REAPPLY=yes accepted" || pass "1 bad NET_DNS_REAPPLY refused"
out="$(run "$FUNC" "rel" 2>&1)" && fail "1 relative NET_ROOT accepted" || pass "1 relative NET_ROOT refused"

# 2. apply, then again
reset "$T/r2" nm; out="$(run "$FUNC" "$T/r2" DRY_RUN=0 2>&1)"; rc=$?
if ((rc == 0)) && [[ "$(held "$W")" == "$target" && "$(held "$E")" == "$target" && "$(held "$S")" == "$target" ]] &&
  [[ "$(grep 'connection modify' "$CALLS" | sed "s#$T/bin/##")" == "$(printf 'nmcli connection modify uuid %s ipv4.dns 8.8.8.8,1.1.1.1 ipv4.dns-options timeout:2,attempts:2\n' "$W" "$E")" ]]; then
  pass "2 DRY_RUN=0 modifies W and E only, with only ipv4.dns + ipv4.dns-options"
else fail "2 modify (rc=$rc): $out / $(cat "$CALLS")"; fi
grep -q "READ $W ipv4.dns=8.8.8.8,1.1.1.1 ipv4.dns-options=timeout:2,attempts:2" <<<"$out" && grep -q "READ $E " <<<"$out" &&
  grep -q 'PENDING active device(s) wlan0' <<<"$out" && ! grep -q 'reapply' "$CALLS" &&
  grep -q 'OK every uplink profile holds .* (3 profile(s), 2 changed)' <<<"$out" &&
  pass "2 reads each back, PENDING wlan0, no reapply by default" || fail "2 read-back: $out"
: >"$CALLS"; out="$(run "$FUNC" "$T/r2" DRY_RUN=0 2>&1)"; rc=$?
((rc == 0)) && (($(modifies) == 0)) && (($(grep -c '^SAME ' <<<"$out") == 3)) && grep -q '(3 profile(s), 0 changed)' <<<"$out" &&
  pass "2 second run: 3 SAME, no modify" || fail "2 second run (rc=$rc): $out / $(cat "$CALLS")"

# 3. the order refusal (row 06 first)
for kind in file stub none; do
  reset "$T/r3" "$kind"; out="$(run "$FUNC" "$T/r3" DRY_RUN=0 2>&1)"; rc=$?
  ((rc != 0)) && grep -q "FATAL .*not the symlink to $NMLINK: run row 06 .*refusing; nothing was changed" <<<"$out" &&
    (($(modifies) == 0)) && [[ "$(held "$E")" == " " ]] && pass "3 DRY_RUN=0, resolv.conf $kind -> refused, nothing changed" ||
    fail "3 $kind (rc=$rc): $out / $(cat "$CALLS")"
done
reset "$T/r3" file; out="$(run "$FUNC" "$T/r3" 2>&1)"; rc=$?
((rc == 0)) && grep -q "NOTE DRY_RUN=0 refuses now: .*is 'not a symlink'" <<<"$out" && grep -q 'OK DRY_RUN 2 of 3' <<<"$out" &&
  (($(modifies) == 0)) && pass "3 dry run with resolv.conf a file: NOTE + plan, nothing changed" || fail "3 dry note (rc=$rc): $out"

# 4. reapply
reset "$T/r4" nm; out="$(run "$FUNC" "$T/r4" DRY_RUN=0 NET_DNS_REAPPLY=1 REAPPLY_WRITES=1 2>&1)"; rc=$?
((rc == 0)) && grep -qx "nmcli device reapply wlan0" "$CALLS" &&
  grep -q 'REAPPLIED wlan0' <<<"$out" && grep -q 'READ resolv.conf: nameserver 8.8.8.8|nameserver 1.1.1.1|nameserver 192.0.2.1|options timeout:2 attempts:2' <<<"$out" &&
  grep -q 'OK every uplink' <<<"$out" && pass "4 NET_DNS_REAPPLY=1 reapplies wlan0, resolv.conf reads the target" ||
  fail "4 reapply (rc=$rc): $out / $(cat "$CALLS")"
: >"$CALLS"; out="$(run "$FUNC" "$T/r4" DRY_RUN=0 NET_DNS_REAPPLY=1 REAPPLY_WRITES=1 2>&1)"; rc=$?
((rc == 0)) && ! grep -q reapply "$CALLS" && (($(modifies) == 0)) && grep -q 'SAME resolv.conf already reads' <<<"$out" &&
  pass "4 again: SAME resolv.conf, no second reapply" || fail "4 again (rc=$rc): $out / $(cat "$CALLS")"
reset "$T/r4" nm; out="$(run "$FUNC" "$T/r4" DRY_RUN=0 NET_DNS_REAPPLY=1 2>&1)"; rc=$?
((rc != 0)) && grep -q "FATAL resolv.conf reads first nameserver '192.0.2.1', options ''" <<<"$out" &&
  pass "4 reapply leaves resolv.conf stale -> FATAL" || fail "4 stale (rc=$rc): $out"
reset "$T/r4" nm; out="$(run "$FUNC" "$T/r4" NET_DNS_REAPPLY=1 2>&1)"; rc=$?
((rc == 0)) && grep -q 'PLAN .*nmcli device reapply wlan0' <<<"$out" && ! grep -q 'device reapply' "$CALLS" &&
  pass "4 dry run plans the reapply, runs none" || fail "4 dry reapply (rc=$rc): $out"

# 5. reading
reset "$T/r5" nm; out="$(run "$FUNC" "$T/r5" DRY_RUN=0 MODIFY_NOOP=1 2>&1)"; rc=$?
((rc != 0)) && grep -q "FATAL nmcli reads $W as ipv4.dns='8.8.8.8,1.1.1.1' ipv4.dns-options='', not" <<<"$out" &&
  pass "5 a modify that does not stick -> FATAL" || fail "5 noop (rc=$rc): $out"
reset "$T/r5" nm; echo attempts:2,timeout:2 >"$ST/$W.ipv4.dns-options"; echo 8.8.8.8,1.1.1.1 >"$ST/$E.ipv4.dns"
echo timeout:2,attempts:2 >"$ST/$E.ipv4.dns-options"
out="$(run "$FUNC" "$T/r5" DRY_RUN=0 ESCAPE=1 2>&1)"; rc=$?
((rc == 0)) && (($(modifies) == 0)) && grep -qx "SAME $W" <<<"$out" && grep -q "ipv4.dns-options=timeout:2,attempts:2" <<<"$out" &&
  pass "5 escaped colons and another option order read as SAME" || fail "5 escape/order (rc=$rc): $out"
reset "$T/r5" nm; echo 1.1.1.1,8.8.8.8 >"$ST/$S.ipv4.dns"; out="$(run "$FUNC" "$T/r5" 2>&1)"; rc=$?
((rc == 0)) && grep -q "PLAN .*modify uuid $S " <<<"$out" && pass "5 nameservers in the other order -> changed" ||
  fail "5 dns order (rc=$rc): $out"

# 6. nothing to work on
reset "$T/r6" nm; echo "$L:loopback:yes:lo" >"$ST/list"; out="$(run "$FUNC" "$T/r6" 2>&1)"; rc=$?
((rc != 0)) && grep -q 'FATAL no saved profile of an uplink type (802-3-ethernet 802-11-wireless gsm)' <<<"$out" &&
  pass "6 only loopback -> FATAL" || fail "6 loopback (rc=$rc): $out"
reset "$T/r6" nm; : >"$ST/list"; out="$(run "$FUNC" "$T/r6" 2>&1)"; rc=$?
((rc != 0)) && grep -q 'FATAL nmcli lists no saved profile' <<<"$out" && pass "6 no profile -> FATAL" || fail "6 empty (rc=$rc): $out"

# 7. red controls
# applied_ok <func> - rc 0 when DRY_RUN=0 on a refusing root is refused and a
# good root ends with every uplink profile on target and only the two keys set
applied_ok() {
  local r
  reset "$T/r7" file; run "$1" "$T/r7" DRY_RUN=0 >/dev/null 2>&1 && return 1
  (($(modifies) == 0)) || return 1
  reset "$T/r7" nm; run "$1" "$T/r7" DRY_RUN=0 >/dev/null 2>&1; r=$?
  ((r == 0)) && [[ "$(held "$W")" == "$target" && "$(held "$E")" == "$target" ]] &&
    ! grep -vE 'modify uuid [0-9a-f-]+ ipv4.dns [^ ]+ ipv4.dns-options [^ ]+$' <<<"$(grep 'connection modify' "$CALLS")" >/dev/null
}
applied_ok "$FUNC" && pass "7 the action itself passes the control" || fail "7 the action fails its own control"
red() {
  sed "$2" "$FUNC" >"$T/red.func.sh"
  cmp -s "$FUNC" "$T/red.func.sh" && { fail "7 red control: the sed for '$1' did not change the copy"; return; }
  applied_ok "$T/red.func.sh" && fail "7 red control: $1 not caught" || pass "7 red control: $1 is caught"
}
red "a copy without the refusal" 's/\[\[ "\$dry" == 1 \]\] ||$/true ||/'
red "a copy writing timeout:5" 's/^NDF_OPTS=timeout:2,/NDF_OPTS=timeout:5,/'
red "a copy with the nameservers swapped" 's/^NDF_DNS=8.8.8.8,1.1.1.1/NDF_DNS=1.1.1.1,8.8.8.8/'
red "a copy also setting ipv4.ignore-auto-dns" 's/ipv4.dns-options "\$NDF_OPTS" <\/dev\/null/ipv4.dns-options "$NDF_OPTS" ipv4.ignore-auto-dns yes <\/dev\/null/'

echo "net-dns-fast-failover: $fails failure(s)"
exit $((fails > 0))
