// Generate src/types/mjs-shims.d.ts from the .mjs modules it declares
// (SPL-1751, ui panel 2026-10-13 item 10).
//
// The shim gives typecheck the types of the `~/utils/*.mjs` modules the SFC
// side imports. It was kept in step by hand, so a changed module showed up
// as a typecheck failure well after the change, or not at all: a name the
// module stopped exporting typechecked green and crashed at runtime, a new
// parameter the shim did not know was silently dropped by every caller.
//
// The types themselves cannot be read off untyped JS, so the declaration
// text already in the shim is kept, byte for byte. Everything else is
// derived from the code on every run:
//   - a `declare module` whose .mjs file is gone is removed;
//   - a value the shim declares but the module no longer exports is removed
//     (types and interfaces stay: they have no runtime twin);
//   - a name a .vue / .ts file imports from a declared module, which the
//     module exports but the shim does not declare, is added with the
//     declaration tsc infers from the JS (`--allowJs --declaration`);
//   - a declared function that takes fewer parameters than the JS one is
//     reported: only a person can type the new parameter.
// The other src/types/*.d.ts files declare names for the same modules (the
// blocks merge); they count as declared and are checked, never rewritten.
//
// Usage:
//   node src/node/generate-mjs-shims.mjs           # rewrite the shim (pnpm run shims)
//   node src/node/generate-mjs-shims.mjs --check   # exit 1 on any drift (pnpm run shims:check)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import ts from "typescript"

const __dirname = dirname(fileURLToPath(import.meta.url))
export const SRC = join(__dirname, "..")
export const SHIM = join(SRC, "types/mjs-shims.d.ts")

export const HEADER = [
  "// Generated by src/node/generate-mjs-shims.mjs (pnpm run shims). Edit a",
  "// declaration's types here; which modules and names appear is derived from",
  "// the .mjs code, and tests/unit/mjs-shims-drift.test.mjs fails on drift.",
  "",
].join("\n")

const MOD_PREFIX = "~/"

const hasModifier = (node, kind) => ts.canHaveModifiers(node) && (ts.getModifiers(node) ?? []).some((m) => m.kind === kind)
const hasExport = (node) => hasModifier(node, ts.SyntaxKind.ExportKeyword)

function paramArity(params) {
  const list = params.filter((p) => !(ts.isIdentifier(p.name) && p.name.text === "this"))
  const rest = list.some((p) => p.dotDotDotToken)
  const required = list.filter((p) => !p.questionToken && !p.initializer && !p.dotDotDotToken).length
  return { total: rest ? Infinity : list.length, required }
}

// The runtime names a JS module exports, each with its arity when it is a function.
export function scanModule(source, fileName = "m.mjs", follow = () => null) {
  const sf = ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
  const out = new Map()
  const put = (name, arity = null) => {
    const prev = out.get(name)
    if (!prev || (arity && (!prev.arity || arity.total > prev.arity.total))) out.set(name, { arity })
  }
  for (const st of sf.statements) {
    if (ts.isFunctionDeclaration(st) && hasExport(st)) {
      put(hasModifier(st, ts.SyntaxKind.DefaultKeyword) ? "default" : st.name.text, paramArity(st.parameters))
    } else if (ts.isClassDeclaration(st) && hasExport(st)) {
      put(hasModifier(st, ts.SyntaxKind.DefaultKeyword) ? "default" : st.name.text)
    } else if (ts.isVariableStatement(st) && hasExport(st)) {
      for (const d of st.declarationList.declarations) {
        if (!ts.isIdentifier(d.name)) continue
        const init = d.initializer
        const fn = init && (ts.isArrowFunction(init) || ts.isFunctionExpression(init))
        put(d.name.text, fn ? paramArity(init.parameters) : null)
      }
    } else if (ts.isExportAssignment(st)) {
      put("default")
    } else if (ts.isExportDeclaration(st) && !st.isTypeOnly) {
      reExports(st, put, follow)
    }
  }
  return out
}

// `export { a as b }`, `export * as ns from`, `export * from` (followed).
function reExports(st, put, follow) {
  const clause = st.exportClause
  if (clause && ts.isNamedExports(clause)) {
    for (const el of clause.elements) if (!el.isTypeOnly) put(el.name.text)
    return
  }
  if (clause) return put(clause.name.text)
  const inner = st.moduleSpecifier && follow(st.moduleSpecifier.text)
  for (const [n, v] of inner ?? []) if (n !== "default") put(n, v.arity)
}

function stmtName(st) {
  if (ts.isFunctionDeclaration(st) || ts.isClassDeclaration(st)) return { name: st.name?.text, value: true }
  if (ts.isTypeAliasDeclaration(st) || ts.isInterfaceDeclaration(st)) return { name: st.name.text, value: false }
  if (ts.isVariableStatement(st)) {
    const d = st.declarationList.declarations[0]
    return { name: ts.isIdentifier(d.name) ? d.name.text : undefined, value: true }
  }
  return { name: undefined, value: false }
}

const showArity = (a) => `${a.required}..${a.total === Infinity ? "n" : a.total}`

const moduleBlocks = (sf) => sf.statements.filter((st) => ts.isModuleDeclaration(st) && ts.isStringLiteral(st.name) && st.body)

// Every `declare module` block of a .d.ts text (or parsed file), as Map<spec, statements[]>.
export function ambientDecls(text, into = new Map()) {
  const sf = typeof text === "string" ? ts.createSourceFile("x.d.ts", text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS) : text
  for (const st of moduleBlocks(sf)) into.set(st.name.text, [...(into.get(st.name.text) ?? []), ...st.body.statements])
  return into
}

// Rebuild the shim text from the code. `env`:
//   loadModule(spec)    -> the module's exports (scanModule), or null when the file is gone
//   imports             -> Map<spec, Set<name>>: value names the .vue / .ts side imports
//   elsewhere           -> ambientDecls of the other .d.ts files (optional)
//   infer(spec, name)   -> a declaration for an undeclared name (optional; --check passes none)
// Returns { text, problems }; problems name every drift, fixed or not.
export function reconcile(shimText, env) {
  const sf = ts.createSourceFile("mjs-shims.d.ts", shimText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
  const problems = []
  const blocks = moduleBlocks(sf)
  const declared = ambientDecls(sf, new Map(env.elsewhere ?? []))
  const lastBlock = new Map()
  for (const st of blocks) lastBlock.set(st.name.text, st)

  let text = shimText.startsWith(HEADER) ? "" : HEADER
  let at = 0
  for (const st of blocks) {
    const spec = st.name.text
    if (!spec.startsWith(MOD_PREFIX) || !spec.endsWith(".mjs")) continue
    const exportsOf = env.loadModule(spec)
    if (!exportsOf) {
      problems.push(`${spec}: declared, but no such file (block removed)`)
      text += shimText.slice(at, st.getFullStart())
      at = st.end
      continue
    }
    const body = st.body
    for (const m of body.statements) {
      const { name, value } = stmtName(m)
      if (value && name && !exportsOf.has(name)) {
        problems.push(`${spec}: declares ${name}, the module does not export it (removed)`)
        text += shimText.slice(at, m.getFullStart())
        at = m.end
        continue
      }
      const js = name && exportsOf.get(name)?.arity
      if (!ts.isFunctionDeclaration(m) || !js) continue
      const overloads = declared.get(spec).filter((o) => ts.isFunctionDeclaration(o) && o.name?.text === name)
      if (m !== overloads[0]) continue
      const dts = overloads.map((o) => paramArity(o.parameters))
      const total = Math.max(...dts.map((a) => a.total))
      const required = Math.min(...dts.map((a) => a.required))
      if (total < js.total) {
        problems.push(`${spec}: ${name} takes ${showArity(js)} parameters, the shim declares ${showArity({ total, required })} (type it by hand)`)
      }
    }
    if (st !== lastBlock.get(spec)) continue
    const have = new Set(declared.get(spec).map((m) => stmtName(m).name))
    const missing = [...(env.imports.get(spec) ?? [])].filter((n) => exportsOf.has(n) && !have.has(n)).sort()
    for (const n of missing) {
      const decl = env.infer?.(spec, n)
      problems.push(`${spec}: ${n} is imported by the SFC side but not declared${decl ? " (added from tsc)" : ""}`)
      if (!decl) continue
      text += shimText.slice(at, body.statements.end)
      at = body.statements.end
      text += "\n" + decl.split("\n").map((l) => (l ? "  " + l : l)).join("\n")
    }
  }
  text += shimText.slice(at)
  return { text, problems }
}

function walk(dir, exts, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) walk(p, exts, out)
    else if (exts.some((x) => e.name.endsWith(x)) && !e.name.endsWith(".d.ts")) out.push(p)
  }
  return out
}

// Value names each `~/…mjs` module is imported for by the .vue / .ts sources.
export function scanImports(srcDir = SRC) {
  const imports = new Map()
  const re = /import\s+(?!type\b)(?:[\w$]+\s*,\s*)?\{([^}]*)\}\s*from\s*['"](~\/[^'"]+\.mjs)['"]/g
  for (const f of walk(srcDir, [".vue", ".ts"])) {
    for (const [, list, spec] of readFileSync(f, "utf8").matchAll(re)) {
      const set = imports.get(spec) ?? new Set()
      for (const part of list.split(",")) {
        const el = part.trim()
        if (!el || el.startsWith("type ")) continue
        set.add(el.split(/\s+as\s+/)[0].trim())
      }
      imports.set(spec, set)
    }
  }
  return imports
}

export function moduleLoader(srcDir = SRC) {
  const cache = new Map()
  const load = (abs) => {
    if (cache.has(abs)) return cache.get(abs)
    cache.set(abs, new Map())
    const res = existsSync(abs)
      ? scanModule(readFileSync(abs, "utf8"), abs, (rel) => (rel.startsWith(".") ? load(resolve(dirname(abs), rel)) : null))
      : null
    cache.set(abs, res)
    return res
  }
  return (spec) => load(join(srcDir, spec.slice(MOD_PREFIX.length)))
}

// The declaration tsc infers for one export of a JS module, in `export …` form.
export function tscInfer(srcDir = SRC) {
  const emitted = new Map()
  return (spec, name) => {
    const abs = join(srcDir, spec.slice(MOD_PREFIX.length))
    if (!emitted.has(abs)) {
      let dts = ""
      const opts = { allowJs: true, declaration: true, emitDeclarationOnly: true, skipLibCheck: true, noResolve: true, target: ts.ScriptTarget.ESNext, module: ts.ModuleKind.ESNext }
      ts.createProgram([abs], opts).emit(undefined, (_f, data) => { dts = data })
      emitted.set(abs, ts.createSourceFile("out.d.ts", dts, ts.ScriptTarget.Latest, true))
    }
    const st = emitted.get(abs).statements.find((s) => stmtName(s).name === name)
    return st ? st.getText().replace(/^export declare /, "export ") : null
  }
}

function main() {
  const check = process.argv.includes("--check")
  const shimText = readFileSync(SHIM, "utf8")
  const elsewhere = new Map()
  for (const f of readdirSync(dirname(SHIM)).filter((f) => f.endsWith(".d.ts")).sort()) {
    if (join(dirname(SHIM), f) !== SHIM) ambientDecls(readFileSync(join(dirname(SHIM), f), "utf8"), elsewhere)
  }
  const env = { loadModule: moduleLoader(), imports: scanImports(), elsewhere, infer: check ? null : tscInfer() }
  const { text, problems } = reconcile(shimText, env)
  const rel = relative(process.cwd(), SHIM)
  for (const p of problems) console.log(`  ${check ? "FAIL" : "drift"} ${p}`)
  if (check) {
    const stale = text !== shimText && problems.length === 0
    if (stale) console.log(`  FAIL ${rel} is not the generator's output: run pnpm run shims`)
    const failed = problems.length + (stale ? 1 : 0)
    console.log(failed ? `\nmjs-shims: ${failed} FAILED` : `mjs-shims: ${rel} matches the code`)
    process.exit(failed ? 1 : 0)
  }
  if (text !== shimText) writeFileSync(SHIM, text)
  const manual = problems.filter((p) => p.endsWith("(type it by hand)") || p.endsWith("not declared"))
  console.log(`mjs-shims: ${text !== shimText ? "rewrote" : "unchanged"} ${rel}${manual.length ? `, ${manual.length} left to type by hand` : ""}`)
  process.exit(manual.length ? 1 : 0)
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main()
